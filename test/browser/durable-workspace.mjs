import assert from 'node:assert/strict';
import fs from 'node:fs';
import { startFixtureServer } from './fixture-server.mjs';
const { chromium } = await import(process.env.UNPROMPTED_PLAYWRIGHT_MODULE || 'playwright');
const fixture = await startFixtureServer({ ruleDemo: false });
const errors = [], checks = [], output = process.env.UNPROMPTED_BROWSER_OUTPUT || 'outputs/durable-validation';
fs.mkdirSync(output, { recursive: true });
let browser, taskFixture;
try {
  browser = await chromium.launch({ channel: process.env.UNPROMPTED_BROWSER_CHANNEL || undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'en-US' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.base + '/#memory');
  await page.locator('#languageSelect').selectOption('en');
  await page.locator('[data-durable-add="fact"]').click();
  await page.locator('#durableDialog textarea[name=text]').fill('Weekly notes: results first, risks second.');
  await page.locator('#durableDialog [type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  await page.locator('#durableMemoryContent').filter({ hasText: 'Weekly notes: results first' }).waitFor();
  checks.push('grounded memory can be saved directly in the persistent workspace');
  await page.locator('[data-durable-add="policy"]').click();
  await page.locator('#durableDialog [name=identity]').fill('alex@example.test');
  await page.locator('#durableDialog [name=confirmed]').check();
  await page.locator('#durableDialog [type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  await page.locator('#policyContent [data-policy-disable]').waitFor();
  assert.match(await page.locator('#policyContent').textContent(), /Active/);
  checks.push('an exact provider identity becomes an explicit visible rule');
  await page.locator('#policyContent [data-policy-disable]').click();
  await page.waitForFunction(() => !document.querySelector('#policyContent [data-policy-disable]'));
  checks.push('a rule can be stopped with one click');
  await page.locator('#durableMemoryContent [data-forget-kind]').click();
  await page.locator('#durableDialog [type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  assert.doesNotMatch(await page.locator('#durableMemoryContent').textContent(), /Weekly notes: results first/);
  checks.push('Forget previews dependencies and actually removes a saved memory');
  await page.goto(fixture.base + '/#preferences');
  await page.locator('[data-attention-settings] [name=hourly]').fill('2');
  await page.locator('[data-attention-settings] [name=interval]').fill('15');
  await page.locator('[data-attention-settings] [name=quietStart]').fill('22');
  await page.locator('[data-attention-settings] [name=quietEnd]').fill('8');
  await page.locator('[data-attention-settings] [type=submit]').click();
  await page.waitForFunction(async () => (await (await fetch('/api/durable')).json()).attention.policy.maxInteractivePerHour === 2);
  await page.reload();
  await page.locator('[data-attention-settings]').waitFor();
  assert.equal(await page.locator('[name=hourly]').inputValue(), '2');
  assert.equal(await page.locator('[name=quietStart]').inputValue(), '22');
  assert.equal(await page.locator('[data-learning-promotion]').isChecked(), false);
  checks.push('quiet hours and interruption budget survive reload; autonomous promotion starts off');
  await page.screenshot({ path: output + '/settings-en.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#languageSelect').selectOption('zh-CN');
  await page.goto(fixture.base + '/#memory');
  await page.locator('[data-durable-add="fact"]').click();
  assert.match(await page.locator('#durableDialogTitle').textContent(), /添加记忆/);
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: output + '/memory-mobile-zh.png', fullPage: true });
  await page.keyboard.press('Escape');
  checks.push('Chinese and English controls work on desktop and mobile without horizontal overflow');
  taskFixture = await startFixtureServer({ serverEnv: { UNPROMPTED_STORAGE: 'sqlite' } });
  await page.goto(taskFixture.base);
  await page.locator('#taskContent [data-select-task]').first().waitFor();
  await page.locator('#taskContent [data-select-task]').first().click();
  await page.locator('#taskContent [data-edit-draft]').first().waitFor();
  const edit = page.locator('#taskContent [data-edit-draft]').first();
  const taskId = await edit.getAttribute('data-edit-draft');
  await edit.click();
  const draftInput = page.locator('#durableDialog [name=body]');
  await draftInput.fill((await draftInput.inputValue()) + '\nUser clarification.');
  await page.locator('#durableDialog [type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  const stateAfterEdit = await (await page.request.get(taskFixture.base + '/api/state')).json();
  assert.match(stateAfterEdit.tasks.find(task => task.id === taskId).draft.body, /User clarification/);
  assert.equal(stateAfterEdit.outbox.length, 0);
  checks.push('the actual task inspector edits a versioned draft without sending');
  await page.locator('#taskContent [data-task-context="sources"]').first().click();
  await page.locator('#taskContextDialog [data-forget-kind="task"]').click();
  await page.locator('#durableDialog [type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  const stateAfterForget = await (await page.request.get(taskFixture.base + '/api/state')).json();
  assert.equal(stateAfterForget.tasks.some(task => task.id === taskId), false);
  assert.equal(stateAfterForget.outbox.length, 0);
  checks.push('a task source dialog can permanently forget its task and dependent records');
  assert.deepEqual(errors, []);
  assert.equal((await (await page.request.get(fixture.base + '/api/state')).json()).outbox.length, 0);
  fs.writeFileSync(output + '/report.json', JSON.stringify({ passed: checks.length, checks, errors }, null, 2));
  console.log(JSON.stringify({ passed: checks.length, errors, output }));
} finally { await browser?.close(); await taskFixture?.close(); await fixture.close(); }
