import assert from 'node:assert/strict';
import fs from 'node:fs';
import path from 'node:path';
import { startFixtureServer } from './fixture-server.mjs';
const { chromium } = await import(process.env.UNPROMPTED_PLAYWRIGHT_MODULE || 'playwright');
const fixture = await startFixtureServer({ ruleDemo: false });
const output = process.env.UNPROMPTED_BROWSER_OUTPUT || 'outputs/standing-intents';
fs.mkdirSync(output, { recursive: true });
const checks = [], errors = [];
let browser;
try {
  browser = await chromium.launch({ channel: process.env.UNPROMPTED_BROWSER_CHANNEL || undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 } });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.base + '/#memory');
  await page.locator('[data-durable-add="intent"]').click();
  const form = page.locator('[data-durable-form="intent"]');
  await form.locator('[name=description]').fill('Watch supplier quotations');
  await form.locator('[name=outcome]').fill('Prepare a source brief when a quotation changes');
  await form.locator('[name=tokens]').fill('quotation');
  await form.locator('[name=autonomy]').selectOption('prepare');
  await form.locator('[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  await page.locator('#standingIntentContent').filter({ hasText: 'Watch supplier quotations' }).waitFor();
  const saved = (await (await fetch(fixture.base + '/api/standing-intents')).json()).intents[0];
  assert.equal(saved.desiredOutcome, 'Prepare a source brief when a quotation changes');
  checks.push('user can create a bounded standing goal and its outcome survives persistence');
  await page.locator('[data-intent-edit]').click();
  await form.locator('[name=outcome]').fill('Prepare a source brief with open risks');
  await form.locator('[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  await page.locator('#standingIntentContent').filter({ hasText: 'Prepare a source brief with open risks' }).waitFor();
  checks.push('editing a goal updates its version and visible outcome');
  await page.locator('[data-intent-transition][data-operation=pause]').click();
  await page.locator('[data-intent-transition][data-operation=resume]').waitFor();
  await page.reload();
  await page.locator('[data-intent-transition][data-operation=resume]').click();
  await page.locator('[data-intent-transition][data-operation=pause]').waitFor();
  checks.push('pause survives reload and resume is explicit');
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('[data-intent-edit]').click();
  assert.ok(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1));
  await page.screenshot({ path: output + '/standing-goal-mobile.png', fullPage: true });
  await page.keyboard.press('Escape');
  await page.locator('[data-intent-transition][data-operation=disable]').click();
  await page.waitForFunction(() => !document.querySelector('[data-intent-transition]'));
  assert.equal((await (await fetch(fixture.base + '/api/standing-intents')).json()).intents[0].status, 'disabled');
  checks.push('mobile editing fits and disabling closes the standing goal');
  const folder = path.join(fixture.directory, 'selected-work'); fs.mkdirSync(folder);
  const filename = path.join(folder, 'Procedure.md'); fs.writeFileSync(filename, '# Lobby procedure\nKeep exits clear.');
  const selected = await page.request.post(fixture.base + '/api/setup/local-sources/local_files/select', { data: { path: folder, observe: false } });
  assert.equal(selected.status(), 200);
  await page.locator('[data-durable-add="intent"]').click();
  await form.locator('[name=description]').fill('Review lobby safety');
  await form.locator('[name=outcome]').fill('Prepare a safety note for review');
  await form.locator('[name=connector]').selectOption('local_files');
  await form.locator('[name=eventType]').selectOption('document.modified');
  await form.locator('[name=tokens]').fill('lobby');
  await form.locator('[name=autonomy]').selectOption('prepare');
  await form.locator('[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#durableDialog').open);
  fs.writeFileSync(filename, '# Lobby procedure\nKeep both emergency exits clear.');
  assert.equal((await page.request.post(fixture.base + '/api/connectors/sync', { data: {} })).status(), 200);
  await page.goto(fixture.base + '/#home');
  const row = page.locator('#taskContent [data-task-card]').filter({ hasText: 'Review lobby safety' });
  await row.locator('[data-select-task]').click();
  await page.locator('[data-accept-prepared]').waitFor();
  assert.match(await page.locator('#taskContent .ws-inspector').innerText(), /Keep both emergency exits clear/);
  await page.screenshot({ path: output + '/local-source-review-mobile.png', fullPage: true });
  const acceptedId = await page.locator('[data-accept-prepared]').getAttribute('data-accept-prepared');
  const suppressed = await page.request.post(fixture.base + '/api/policies', { data: { instruction: 'Pause preparation for now', predicate: { op: 'always' }, effect: { type: 'suppress' } } });
  assert.equal(suppressed.status(), 200);
  const rule = (await suppressed.json()).policy;
  await page.waitForFunction(async id => (await (await fetch('/api/state')).json()).tasks.find(task => task.id === id)?.activationHold, acceptedId);
  await page.locator('#taskContent .ws-state-notice').filter({ hasText: /因规则暂停|Paused by a rule/ }).waitFor();
  assert.equal(await page.locator('[data-accept-prepared]').count(), 0);
  assert.equal((await page.request.post(fixture.base + `/api/policies/${rule.id}/disable`, { data: { expectedVersion: rule.version } })).status(), 200);
  await page.locator('[data-accept-prepared]').waitFor();
  checks.push('suppression visibly holds an existing preparation and disabling its rule resumes review');
  await page.locator('[data-accept-prepared]').click();
  await page.waitForFunction(async id => (await (await fetch('/api/state')).json()).tasks.find(task => task.id === id)?.completion?.kind === 'user_accepted_preparation', acceptedId);
  await page.locator('#taskContent').filter({ hasText: /你已接受|Accepted/ }).waitFor();
  assert.match(await page.locator('#taskContent').innerText(), /你已接受|Accepted/);
  assert.equal(await page.locator('[data-accept-prepared]').count(), 0);
  checks.push('selected local source -> activation -> source preparation -> pinned user review completes without a provider write');
  assert.deepEqual(errors, []);
} finally {
  fs.writeFileSync(output + '/checks.json', JSON.stringify({ checks, errors }, null, 2));
  await browser?.close(); await fixture.close();
}
console.log(JSON.stringify({ checks, errors }, null, 2));
