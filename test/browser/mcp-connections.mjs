import assert from 'node:assert/strict';
import fs from 'node:fs';
import http from 'node:http';
import { fileURLToPath } from 'node:url';
import { startFixtureServer } from './fixture-server.mjs';
import { reply } from '../fixtures/mcp-server.mjs';

const { chromium } = await import(process.env.UNPROMPTED_PLAYWRIGHT_MODULE || 'playwright');
const output = process.env.UNPROMPTED_BROWSER_OUTPUT || 'outputs/mcp-validation';
fs.mkdirSync(output, { recursive: true });
const seen = [];
const service = http.createServer(async (req, res) => {
  if (req.method !== 'POST') { res.writeHead(405); return res.end(); }
  let body = ''; for await (const chunk of req) body += chunk;
  const message = JSON.parse(body); seen.push(message.method);
  if (req.headers.authorization !== 'Bearer browser-private-token') { res.writeHead(401); return res.end(); }
  const result = await reply(message);
  if (message.id == null) { res.writeHead(202); return res.end(); }
  res.writeHead(200, { 'content-type': 'application/json' });
  res.end(JSON.stringify({ jsonrpc: '2.0', id: message.id, result }));
});
await new Promise(resolve => service.listen(0, '127.0.0.1', resolve));
const fixture = await startFixtureServer({ ruleDemo: false });
let browser;
const errors = [], checks = [];
const check = id => checks.push({ id, passed: true });
try {
  browser = await chromium.launch({ channel: process.env.UNPROMPTED_BROWSER_CHANNEL || undefined, headless: true });
  const page = await browser.newPage({ viewport: { width: 1440, height: 1000 }, locale: 'en-US' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.base + '/#sources');
  await page.locator('#languageSelect').selectOption('en');
  await page.locator('[data-mcp-add]').click();
  const dialog = page.locator('#mcpDialog');
  await dialog.locator('[name=name]').fill('work-tools');
  await dialog.locator('[name=url]').fill(`http://127.0.0.1:${service.address().port}/mcp`);
  await dialog.locator('[name=token]').fill('browser-private-token');
  await dialog.locator('[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#mcpDialog').open);
  const server = page.locator('[data-mcp-server="work-tools"]');
  await server.locator('[data-status="connected"]').waitFor();
  assert.match(await server.textContent(), /3\/5 tools enabled/);
  assert.ok(seen.includes('initialize') && seen.includes('tools/list'));
  const setup = await (await page.request.get(fixture.base + '/api/setup')).json();
  assert.ok(!JSON.stringify(setup).includes('browser-private-token'));
  assert.equal(await dialog.locator('[name=token]').inputValue(), '');
  check('remote-url-and-token-connect-to-a-real-mcp-service-without-secret-echo');
  await server.locator('summary').click();
  assert.equal(await server.locator('[data-mcp-tool="lookup"]').isChecked(), true);
  assert.equal(await server.locator('[data-mcp-tool="write_item"]').isChecked(), false);
  await server.locator('[data-mcp-tool="lookup"]').uncheck();
  await page.waitForFunction(() => !document.querySelector('[data-mcp-server="work-tools"] [data-mcp-tool="lookup"]').checked && !document.querySelector('[data-mcp-server="work-tools"] [data-mcp-tool="lookup"]').disabled);
  let status = await (await page.request.get(fixture.base + '/api/mcp')).json();
  assert.equal(status.servers[0].tools.find(tool => tool.name === 'lookup').allowed, false);
  assert.equal(status.servers[0].tools.find(tool => tool.name === 'slow').allowed, true);
  check('tool-access-is-explicit-and-can-be-revoked-with-one-checkbox');
  await server.locator('[data-mcp-action="disable"]').click();
  await server.locator('[data-mcp-action="enable"]').waitFor();
  status = await (await page.request.get(fixture.base + '/api/mcp')).json();
  assert.equal(status.servers[0].enabled, false);
  await server.locator('[data-mcp-action="enable"]').click();
  await server.locator('[data-status="connected"]').waitFor();
  check('disable-and-enable-close-and-reconnect-the-service');
  await page.locator('[data-mcp-add]').click();
  await dialog.locator('[data-mcp-mode="json"]').click();
  await dialog.locator('[name=config]').fill('{bad');
  await dialog.locator('[type=submit]').click();
  await dialog.locator('#mcpFormError').filter({ hasText: 'Invalid MCP JSON' }).waitFor();
  assert.equal(await dialog.locator('[name=config]').inputValue(), '{bad');
  await dialog.locator('[name=config]').fill(JSON.stringify({ mcpServers: { local: { command: process.execPath, args: [fileURLToPath(new URL('../fixtures/mcp-server.mjs', import.meta.url)), '--stdio'], env: { MCP_RESOURCES_ONLY: 'yes' } } } }));
  await dialog.locator('[type=submit]').click();
  await page.waitForFunction(() => !document.querySelector('#mcpDialog').open);
  await page.locator('[data-mcp-server="local"] [data-status="connected"]').waitFor();
  const local = page.locator('[data-mcp-server="local"]');
  await local.locator('summary').filter({ hasText: 'Resources and access' }).click();
  const resource = local.locator('[data-mcp-resource]');
  assert.equal(await resource.isChecked(), false);
  await resource.check();
  await page.waitForFunction(() => document.querySelector('[data-mcp-server="local"] [data-mcp-resource]')?.checked && !document.querySelector('[data-mcp-server="local"] [data-mcp-resource]').disabled);
  assert.equal((await (await page.request.get(fixture.base + '/api/mcp')).json()).servers.find(item => item.id === 'local').resources[0].allowed, true);
  check('resource-only-server-requires-explicit-resource-grant');
  check('pasted-stdio-config-runs-a-real-server-and-invalid-json-preserves-input');
  await page.reload();
  await page.locator('[data-mcp-server="local"] [data-status="connected"]').waitFor();
  assert.equal(await page.locator('[data-mcp-server="local"] [data-mcp-resource]').isChecked(), true);
  assert.equal(await page.locator('[data-mcp-server]').count(), 2);
  check('connections-survive-page-reload');
  const crossOrigin = await page.request.post(fixture.base + '/api/mcp/import', { headers: { origin: 'https://foreign.test' }, data: { config: { mcpServers: { unwanted: { command: 'node' } } } } });
  assert.equal(crossOrigin.status(), 403);
  check('cross-origin-configuration-writes-are-rejected');
  await page.screenshot({ path: output + '/connections-desktop.png', fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.locator('#languageSelect').selectOption('zh-CN');
  if (await page.evaluate(() => document.documentElement.dataset.theme !== 'dark')) await page.locator('#themeToggle').click();
  await page.locator('[data-mcp-add]').click();
  assert.equal(await dialog.locator('[name=name]').isVisible(), true);
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth), true);
  const bounds = await dialog.boundingBox(); assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 390);
  await page.screenshot({ path: output + '/connections-mobile-dark.png', fullPage: true });
  await page.keyboard.press('Escape');
  check('english-chinese-and-mobile-dark-mode-remain-usable');
  await page.locator('[data-mcp-server="local"] [data-mcp-action="remove"]').click();
  await page.waitForFunction(() => !document.querySelector('[data-mcp-server="local"]'));
  check('removing-a-server-clears-its-configuration');
  assert.deepEqual(errors, []);
  fs.writeFileSync(output + '/mcp-contract.json', JSON.stringify({ checks, pageErrors: errors }, null, 2) + '\n');
  console.log(`MCP browser contract passed: ${checks.length} checks.`);
} finally {
  await browser?.close(); await fixture.close();
  await new Promise(resolve => { service.closeAllConnections(); service.close(resolve); });
}
