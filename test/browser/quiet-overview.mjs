import assert from 'node:assert/strict';
import fs from 'node:fs';
import { startFixtureServer } from './fixture-server.mjs';

const { chromium } = await import(process.env.UNPROMPTED_PLAYWRIGHT_MODULE || 'playwright');
const fixture = await startFixtureServer({ demo: true, serverEnv: { UNPROMPTED_DEMO_MEMORY_COUNT: '100' } });
const browser = await chromium.launch({ channel: process.env.UNPROMPTED_BROWSER_CHANNEL || undefined, headless: true });
const output = process.env.UNPROMPTED_BROWSER_OUTPUT || 'outputs/quiet-overview';
fs.mkdirSync(output, { recursive: true });
const checks = [], errors = [];
try {
  const page = await browser.newPage({ viewport: { width: 1440, height: 960 }, locale: 'zh-CN', reducedMotion: 'reduce' });
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(fixture.base);
  await page.locator('#taskContent [data-select-task]').first().waitFor();
  assert.equal(await page.locator('#taskContent').getAttribute('data-mode'), 'field');
  assert.equal(await page.locator('#viewHome [data-workspace-mode]').count(), 0);
  assert.equal(await page.locator('#viewHome [role="tablist"]').count(), 0);
  assert.equal(await page.locator('.navigation [data-view="attention"]').count(), 0);
  assert.equal(await page.locator('[data-open-first-decision], [data-record-toggle]').count(), 0);
  assert.doesNotMatch(await page.locator('#agentStatus').innerText(), /处理这件|查看记录|收起记录/);
  const log = page.locator('#homeAmbient [data-go="activity"]');
  await log.waitFor();
  assert.equal(await log.evaluate(node => Boolean(node.closest('h3'))), false);
  assert.notEqual(await log.evaluate(node => getComputedStyle(node).fontSize), '11px');
  await log.click();
  assert.equal(new URL(page.url()).hash, '#activity');
  assert.equal(await page.locator('#viewActivity').isVisible(), true);
  assert.equal(await page.locator('#viewHome').isVisible(), false);
  assert.equal(await page.locator('#homeRecord').isVisible(), true);
  assert.ok(await page.locator('#eventContent .trace-day-group').count() >= 1);
  const firstRecord = page.locator('#eventContent .trace-event').first();
  assert.equal(await firstRecord.locator(':scope > summary').evaluate(node => getComputedStyle(node).display), 'grid');
  assert.equal(await firstRecord.evaluate(node => node.open), false);
  assert.equal(await firstRecord.locator('.trace-event-detail').isVisible(), false);
  assert.ok(await firstRecord.getAttribute('data-tone'));
  await firstRecord.locator('summary').click();
  assert.equal(await firstRecord.locator('.trace-event-detail').isVisible(), true);
  await firstRecord.locator('[data-select-task]').click();
  await page.locator('#taskContent .ws-task-page').waitFor();
  assert.equal(await page.locator('#viewActivity').isVisible(), false);
  await page.locator('[data-view="activity"]').click();
  assert.equal(await page.locator('#pageCrumb').textContent(), '日志');
  await page.locator('#eventContent .trace-event[open]').waitFor();
  await page.locator('#activitySearch').fill('Northstar');
  assert.ok(await page.locator('#eventContent .trace-event').count() >= 1);
  await page.screenshot({ path: `${output}/activity-editorial-desktop.png`, fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 390, height: 844 });
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.screenshot({ path: `${output}/activity-editorial-mobile.png`, fullPage: true, animations: 'disabled' });
  await page.setViewportSize({ width: 1440, height: 960 });
  await page.locator('#activitySearch').fill('');
  await page.locator('[data-view="home"]').click();
  await page.locator('#taskContent [data-close-inspector]').click();
  assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
  await page.locator('[data-view="home"]').click();
  assert.equal(await page.locator('#taskStatusFilter').inputValue(), 'all');
  await page.locator('#taskStatusFilter').evaluate(node => { node.value = 'working'; node.dispatchEvent(new Event('change', { bubbles: true })); });
  assert.equal(await page.locator('#taskStatusFilter').inputValue(), 'working');
  assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
  await page.locator('#taskStatusFilter').evaluate(node => { node.value = 'all'; node.dispatchEvent(new Event('change', { bubbles: true })); });
  await page.goto(fixture.base + '/#attention');
  await page.waitForFunction(() => document.querySelector('#taskStatusFilter')?.value === 'attention');
  assert.equal(await page.locator('#viewAttention').isVisible(), false);
  assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
  await page.locator('[data-view="memory"]').click();
  await page.keyboard.press('n');
  await page.waitForFunction(() => location.hash === '#home' && document.querySelector('#taskStatusFilter')?.value === 'attention');
  const queued = await page.locator('#taskContent [data-task-card]').count();
  assert.equal(await page.locator('.ws-detail-drawer').count() > 0, queued > 0);
  await page.locator('[data-view="home"]').click();
  assert.equal(await page.locator('#taskStatusFilter').inputValue(), 'all');
  if (await page.locator('.ws-detail-drawer').count()) await page.keyboard.press('Escape');
  assert.equal(await page.locator('#taskContent .ws-inspector, .ws-workbench-detail').count(), 0);
  const taskId = await page.locator('#taskContent [data-select-task]').first().getAttribute('data-select-task');
  await page.screenshot({ path: `${output}/field-cards-desktop.png`, animations: 'disabled' });
  await page.locator('#taskContent [data-select-task]').first().click();
  await page.locator('.ws-detail-drawer .ws-inspector').waitFor();
  await page.locator('.ws-detail-drawer textarea').fill('还没有提交的方向');
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.ws-detail-drawer').count(), 0);
  assert.equal(await page.evaluate(() => document.activeElement.dataset.selectTask), taskId);
  await page.request.post(`${fixture.base}/api/tasks/${encodeURIComponent(taskId)}/pause`, { data: {} });
  await page.waitForFunction(id => document.querySelector(`[data-task-card="${CSS.escape(id)}"]`)?.dataset.state === 'paused_by_user', taskId);
  assert.equal(await page.locator('.ws-detail-drawer').count(), 0);
  await page.locator('#taskContent [data-select-task]').first().click();
  assert.equal(await page.locator('.ws-detail-drawer textarea').inputValue(), '还没有提交的方向');
  await page.keyboard.press('Escape');
  checks.push('task cards open details explicitly; close retains drafts and live updates never reopen them');

  await page.locator('[data-view="memory"]').click();
  await page.locator('.memory-space-node').first().waitFor();
  assert.equal(await page.locator('.memory-inspector').count(), 0);
  assert.equal(await page.locator('.memory-focus-navigation').count(), 0);
  assert.equal(await page.locator('.memory-space-node').count(), 10);
  assert.equal(await page.locator('.memory-space-edge').count(), 45);
  assert.equal(await page.locator('[data-memory-space-add]').count(), 0);
  assert.equal(await page.locator('[data-memory-view="space"]').getAttribute('aria-pressed'), 'true');
  assert.equal(await page.locator('.memory-demo-note').isVisible(), true);
  const state = await (await page.request.get(fixture.base + '/api/state')).json();
  assert.equal(state.taskMemories.length, 100);
  assert.equal(state.taskMemories.every(memory => memory.origin === 'demo_preview'), true);
  assert.match(await page.locator('.memory-space-graph-footer span').first().textContent(), /^10 条记忆 · 45 条关系$/);
  await page.screenshot({ path: `${output}/memory-100-desktop.png`, animations: 'disabled' });
  const firstFocus = await page.locator('.memory-space-node').first().getAttribute('data-memory-focus');
  await page.locator('.memory-space-node').first().click();
  assert.equal(await page.locator('.memory-inspector').count(), 1);
  assert.equal(await page.locator('.memory-inspector [data-memory-operation]').count(), 0);
  assert.match(await page.locator('.memory-inspector').innerText(), /演示预览为只读/);
  assert.equal(await page.evaluate(() => document.activeElement.matches('.memory-inspector h2')), true);
  await page.screenshot({ path: `${output}/memory-100-open.png`, animations: 'disabled' });
  await page.keyboard.press('Escape');
  assert.equal(await page.locator('.memory-inspector').count(), 0);
  assert.equal(await page.evaluate(() => document.activeElement.dataset.memoryFocus), firstFocus);
  await page.locator('[data-memory-search]').fill('退改');
  await page.waitForFunction(() => document.querySelectorAll('.memory-space-node').length === 1);
  assert.equal(await page.locator('.memory-space-node').getAttribute('data-memory-focus'), 'demo-memory-082');
  assert.match(await page.locator('.memory-space-graph-footer').innerText(), /1 条记忆 · 0 条关系/);
  assert.equal(await page.locator('.memory-space-no-edges').count(), 1);
  await page.locator('[data-memory-search]').fill('写作与沟通');
  await page.waitForFunction(() => document.querySelectorAll('.memory-space-node').length === 10 && document.querySelector('.memory-space-graph-footer')?.textContent.includes('45 条关系'));
  const spaceIds = await page.locator('.memory-space-node').evaluateAll(nodes => nodes.map(node => node.dataset.memoryFocus).sort());
  assert.equal(spaceIds.length, 10);
  await page.locator('[data-memory-view="list"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.memory-library .ws-memory').length === 10);
  assert.equal(await page.locator('[data-memory-view="list"]').getAttribute('aria-pressed'), 'true');
  const listIds = await page.locator('.memory-library .ws-memory').evaluateAll(nodes => nodes.map(node => node.dataset.memoryId).sort());
  assert.deepEqual(listIds, spaceIds);
  assert.equal(await page.locator('.memory-list-note').isVisible(), true);
  await page.locator('[data-memory-search]').fill('退改');
  await page.waitForFunction(() => document.querySelectorAll('.memory-library .ws-memory').length === 1);
  assert.equal(await page.locator('.memory-library .ws-memory').getAttribute('data-memory-id'), 'demo-memory-082');
  await page.locator('[data-memory-view="space"]').click();
  await page.waitForFunction(() => document.querySelectorAll('.memory-space-node').length === 1);
  assert.equal(await page.locator('.memory-space-node').getAttribute('data-memory-focus'), 'demo-memory-082');
  assert.equal(await page.locator('.memory-inspector').count(), 0);
  await page.locator('[data-memory-search]').fill('');
  await page.waitForFunction(() => document.querySelectorAll('.memory-space-node').length === 10);
  for (const width of [320, 390, 768, 1440]) {
    await page.setViewportSize({ width, height: 900 });
    assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true, `${width}px memory space overflows`);
    assert.equal(await page.locator('.memory-space-node').count(), 10);
    assert.equal(await page.locator('.memory-inspector').count(), 0);
    if (width === 390) await page.screenshot({ path: `${output}/memory-100-mobile.png`, fullPage: true, animations: 'disabled' });
  }
  checks.push('100 demo memories expose ten related nodes, search narrows both views to the same ids and the read-only preview never offers mutations');

  for (const mode of ['field', 'index', 'lanes', 'spotlight', 'pulse']) {
    await page.locator('[data-view="preferences"]').click();
    assert.equal(await page.locator('#workspaceViewOptions option').count(), 5);
    await page.selectOption('#workspaceViewOptions', mode);
    await page.locator('[data-view="home"]').click();
    assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
    await page.locator('#taskContent [data-select-task]').first().click();
    assert.equal(await page.locator('#taskContent .ws-inspector').isVisible(), true);
    await page.keyboard.press('Escape');
    assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
  }
  await page.reload();
  await page.waitForFunction(() => document.querySelector('#taskContent')?.dataset.mode === 'pulse');
  assert.equal(await page.locator('#taskContent .ws-inspector').count(), 0);
  checks.push('five views are selected only in settings, remember the preference and never open a task on reload');
  assert.deepEqual(errors, []);
  console.log(JSON.stringify({ checks, errors, output }, null, 2));
} finally {
  await browser.close();
  await fixture.close();
}
