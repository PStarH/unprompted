export function seedDemoMemories(store, { count = 0, demo = false } = {}) {
  if (!demo || !Number.isInteger(count) || count < 1 || count > 100) return 0;
  const at = Date.now();
  const records = collections.flatMap(([entity, deliverable, texts]) => texts.map(text => ({ entity, deliverable, text }))).slice(0, count);
  const missing = records.map((record, index) => ({ ...record, id: `demo-memory-${String(index + 1).padStart(3, '0')}`, updatedAt: new Date(at - index * 3600000).toISOString() })).filter(record => !store.state.taskMemories?.[record.id]);
  if (!missing.length) return 0;
  store.mutate(state => {
    state.taskMemories ||= {};
    for (const record of missing) state.taskMemories[record.id] = {
      id: record.id, text: record.text, taskId: null, origin: 'demo_preview',
      scope: { entity: record.entity, deliverable: record.deliverable },
      createdAt: record.updatedAt, updatedAt: record.updatedAt, deletedAt: null
    };
  });
  return missing.length;
}
